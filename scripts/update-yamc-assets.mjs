import { readFile, writeFile, access, readdir } from "node:fs/promises";
import path from "node:path";
import console from "node:console";
const manifest = JSON.parse(
  await readFile("packages/cat-shit-engine/src/yamc-manifest.json", "utf8"),
);
const entries = [];
for (const [id, sprite] of Object.entries(manifest)) {
  if (!/^yamc\/[a-z-]+\.png$/.test(sprite.imagePath))
    throw new Error(`Invalid local PNG path: ${id}`);
  try {
    await access(path.join("app/assets", sprite.imagePath));
  } catch {
    continue;
  }
  entries.push(
    `  ${JSON.stringify(id)}: require(${JSON.stringify("../assets/" + sprite.imagePath)}),`,
  );
}
await writeFile(
  "app/src/yamcAssets.ts",
  `${entries.length ? "/* eslint-disable @typescript-eslint/no-require-imports -- Metro needs literal local media imports. */\n" : ""}// Generated by node scripts/update-yamc-assets.mjs; absent PNGs use provisional SVG.
import type { ImageSourcePropType } from "react-native";
import type { YamcSpriteId } from "@yac/cat-shit-engine";
export const YAMC_IMAGES: Partial<Record<YamcSpriteId, ImageSourcePropType>> = {
${entries.join("\n")}
};
`,
);
const variants = (await readdir("app/assets/yamc")).filter(
  (n) =>
    /^[a-z-]+-(open|closed|purr)\.png$/.test(n) ||
    /^catshitcoin-(64|128)\.png$/.test(n),
);
await writeFile(
  "app/src/yamcVariants.ts",
  `/* eslint-disable @typescript-eslint/no-require-imports -- Metro local images. */\nimport type { ImageSourcePropType } from 'react-native';\nexport const YAMC_VARIANTS:Record<string,ImageSourcePropType>={\n${variants.map((n) => `  ${JSON.stringify(n.slice(0, -4))}: require(${JSON.stringify("../assets/yamc/" + n)}),`).join("\n")}\n};\n`,
);
console.log(
  `${entries.length}/12 Yamc PNGs registered; remaining poses use SVG placeholders.`,
);
